import type { BackendStatus, StreamStatus } from "../types/domain";

export interface GlobalHeaderProps {
  backendStatus: BackendStatus;
  streamStatus: StreamStatus;
  simulationRunning: boolean;
  onStartStream: () => void;
  onStopStream: () => void;
  onStartSimulation: () => void;
  onStopSimulation: () => void;
}

function streamDotClass(status: StreamStatus): string {
  if (status === "CONNECTED") return "ok live";
  if (status === "CONNECTED_WAITING") return "ok";
  if (status === "CONNECTING") return "warn";
  if (status === "ERROR") return "bad";
  return "";
}

function streamLabel(status: StreamStatus): string {
  switch (status) {
    case "CONNECTED":
      return "LIVE INGESTION";
    case "CONNECTED_WAITING":
      return "CONNECTED — WAITING FOR EVENTS";
    case "CONNECTING":
      return "CONNECTING";
    case "ERROR":
      return "STREAM ERROR";
    default:
      return "DISCONNECTED";
  }
}

export function GlobalHeader({
  backendStatus,
  streamStatus,
  simulationRunning,
  onStartStream,
  onStopStream,
  onStartSimulation,
  onStopSimulation,
}: GlobalHeaderProps) {
  const connected = streamStatus === "CONNECTED" || streamStatus === "CONNECTED_WAITING";

  return (
    <header className="app-header">
      <div className="brand">
        <div className="brand-mark" aria-hidden="true">
          BB
        </div>
        <div className="brand-text">
          <h1>Bug Busters // AIOps Command Center</h1>
          <p>Problem Statement AO-01 · Table T-08</p>
        </div>
      </div>

      <div className="header-status-group">
        <span className="status-pill" title="Whether the FastAPI backend process can be reached — not a claim about where its data comes from.">
          <span className={`status-dot ${backendStatus === "REACHABLE" ? "ok" : backendStatus === "UNREACHABLE" ? "bad" : "warn"}`} />
          BACKEND: {backendStatus === "UNKNOWN" ? "CHECKING…" : backendStatus}
        </span>

        <span className="status-pill" title="This prototype has no production alert source wired in. Every alert shown, backend-reachable or not, is synthetic — fixture-seeded or generated by the demo simulation.">
          <span className="status-dot warn" />
          DATA: SYNTHETIC DEMO
        </span>

        <span className="status-pill" title="Hostnames, IPs and customer identifiers are masked server-side before alerts reach the UI.">
          <span className="status-dot ok" />
          REDACTION: SERVER-SIDE MASKED
        </span>

        <span className="status-pill">
          <span className={`status-dot ${streamDotClass(streamStatus)}`} />
          {streamLabel(streamStatus)}
        </span>

        {!connected ? (
          <button className="btn btn-sm" onClick={onStartStream}>
            Connect Stream
          </button>
        ) : (
          <>
            <button className="btn btn-sm btn-secondary" onClick={onStopStream}>
              Disconnect
            </button>
            {!simulationRunning ? (
              <button className="btn btn-sm" onClick={onStartSimulation}>
                Run Demo Simulation
              </button>
            ) : (
              <button className="btn btn-sm btn-danger" onClick={onStopSimulation}>
                Stop Simulation
              </button>
            )}
          </>
        )}
      </div>
    </header>
  );
}
